#!/usr/bin/env node
/** Generate the package-facing token map from the DTCG-compatible source. */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const designDirectory = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(designDirectory, 'tokens.json');
const outputPath = join(designDirectory, '..', 'packages', 'web', 'src', 'styles', 'tokens.ts');
const siteOutputPath = join(designDirectory, '..', 'apps', 'site', 'src', 'styles', 'varendo-tokens.css');
const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const checkOnly = process.argv.includes('--check');

const kebab = (value) =>
  value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .toLowerCase();

const dimension = (value) => {
  if (typeof value !== 'object' || value === null || typeof value.value !== 'number') return undefined;
  return `${value.value}${value.unit ?? ''}`;
};

const shadow = (value) => {
  if (typeof value !== 'object' || value === null || typeof value.color !== 'string') return undefined;
  const part = (entry) => dimension(entry) ?? '0';
  return `${part(value.offsetX)} ${part(value.offsetY)} ${part(value.blur)} ${part(value.spread)} ${value.color}`;
};

function cssValue(token) {
  const value = token?.$value;
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  if (Array.isArray(value)) {
    if (value.every((item) => typeof item === 'number')) return `cubic-bezier(${value.join(', ')})`;
    if (value.every((item) => item && typeof item === 'object' && item.offsetX !== undefined))
      return value.map(shadow).join(', ');
    return value.join(', ');
  }
  if (value?.hex !== undefined) return value.hex;
  if (value?.offsetX !== undefined) return shadow(value);
  return dimension(value) ?? JSON.stringify(value);
}

function flatten(group, prefix, output) {
  for (const [name, value] of Object.entries(group)) {
    if (name.startsWith('$')) continue;
    const next = [...prefix, name];
    if (value && typeof value === 'object' && '$value' in value) {
      output[`--varendo-${next.map(kebab).join('-')}`] = cssValue(value);
    } else if (value && typeof value === 'object') {
      flatten(value, next, output);
    }
  }
}

const light = {};
const dark = {};
const shared = {};
flatten(source.light, ['color'], light);
flatten(source.dark, ['color'], dark);
// Visualization colors are theme-specific but keep a stable public namespace.
flatten(source.visualization?.light ?? {}, ['visualization'], light);
flatten(source.visualization?.dark ?? {}, ['visualization'], dark);
for (const [group, value] of Object.entries(source)) {
  if (['$description', '$extensions', 'light', 'dark', 'visualization'].includes(group)) continue;
  flatten({ [group]: value }, [], shared);
}

const render = (value) =>
  JSON.stringify(value, null, 2)
    .replace(/^/gm, '  ')
    .replace(/^  \{/m, '{')
    .replace(/\n  \}/g, '\n}');
const cssDeclarations = (value) =>
  Object.entries(value)
    .map(([name, token]) => `  ${name}: ${token};`)
    .join('\n');
const names = [...new Set([...Object.keys(light), ...Object.keys(dark), ...Object.keys(shared)])];
const rawOutput = `/** Generated by design/generate-web-tokens.mjs from design/tokens.json. */
export type VarendoThemeMode = "light" | "dark";
export type VarendoTokenName = ${names.map((name) => JSON.stringify(name)).join(' | ')};
export type VarendoTokenValues = Readonly<Partial<Record<VarendoTokenName, string>>>;

export const VARENDO_LIGHT_TOKENS = ${render(light)} as const as VarendoTokenValues;
export const VARENDO_DARK_TOKENS = ${render(dark)} as const as VarendoTokenValues;
export const VARENDO_SHARED_TOKENS = ${render(shared)} as const as VarendoTokenValues;
export const VARENDO_TOKEN_NAMES = ${JSON.stringify(names, null, 2)} as const;

export const VARENDO_THEME_TOKENS = {
  light: VARENDO_LIGHT_TOKENS,
  dark: VARENDO_DARK_TOKENS,
  shared: VARENDO_SHARED_TOKENS,
} as const;

export function getVarendoToken(mode: VarendoThemeMode, name: VarendoTokenName): string {
  return VARENDO_THEME_TOKENS[mode][name] ?? VARENDO_SHARED_TOKENS[name] ?? "";
}
`;
const output = await format(rawOutput, {
  parser: 'typescript',
  printWidth: 120,
  singleQuote: true,
});
const rawSiteOutput = `/* Generated by design/generate-web-tokens.mjs from design/tokens.json. */
:root {
${cssDeclarations(shared)}
${cssDeclarations(light)}
  color-scheme: light;
}

:root[data-theme='dark'] {
${cssDeclarations(dark)}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']):not([data-theme='dark']) {
${cssDeclarations(dark)}
    color-scheme: dark;
  }
}
`;
const siteOutput = await format(rawSiteOutput, { parser: 'css', singleQuote: true });
if (checkOnly) {
  let current;
  let currentSite;
  try {
    current = await readFile(outputPath, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') current = undefined;
    else throw error;
  }
  try {
    currentSite = await readFile(siteOutputPath, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') currentSite = undefined;
    else throw error;
  }
  if (current !== output) {
    console.error(`Generated token file is stale: ${outputPath}`);
    process.exitCode = 1;
  }
  if (currentSite !== siteOutput) {
    console.error(`Generated token file is stale: ${siteOutputPath}`);
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
  await writeFile(siteOutputPath, siteOutput);
}
